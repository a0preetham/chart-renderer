// Regenerates fixtures.js from the crate's test fixtures.
//
//   node bench/workerd/sync-fixtures.mjs
//
// The benchmark deliberately runs the same specs the test suite does, so a
// timing here always corresponds to a chart that is covered by tests. Copying
// them in at build time rather than maintaining a second list is what keeps the
// two from drifting.

import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const fixturesDir = join(here, '../../crates/core/tests/fixtures');

const entries = readdirSync(fixturesDir)
  .filter((f) => f.endsWith('.json') && !f.endsWith('.vega.json'))
  .sort()
  .map((f) => {
    const name = f.replace(/\.json$/, '');
    const spec = JSON.parse(readFileSync(join(fixturesDir, f), 'utf8'));
    const body = JSON.stringify(spec, null, 2)
      .split('\n')
      .map((line, i) => (i === 0 ? line : '  ' + line))
      .join('\n');
    return `  ${JSON.stringify(name)}: ${body}`;
  });

writeFileSync(
  join(here, 'fixtures.js'),
  `// Generated by \`node bench/workerd/sync-fixtures.mjs\` — do not edit.
//
// The benchmark runs the same specs the test suite does, so a timing here
// always corresponds to a chart that is covered by tests.

export const FIXTURES = {
${entries.join(',\n')}
};
`
);

console.log(`wrote ${entries.length} fixtures`);
